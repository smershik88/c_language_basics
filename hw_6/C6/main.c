#include <inttypes.h>
#include <stdio.h>
#include <stdlib.h>

/*
Сколько зерен на доске
Когда создатель шахмат, древнеиндийский мудрец и математик Сисса бен Дахир, показал своё изобретение
Правителю страны, тому так понравилась игра, что он позволил изобретателю право самому выбрать
награду. Мудрец попросил у Повелителя за первую клетку шахматной доски заплатить ему одно зерно
риса, за второе — два, за третье — четыре и т. д., удваивая количество зёрен на каждой следующей
клетке. Помоги повелителю сосчитать сколько зерен на какой клетке лежит. Необходимо составить
функцию, которая определяет, сколько зерен попросил положить на N-ую клетку изобретатель шахмат (на
1-ую – 1 зерно, на 2-ую – 2 зерна, на 3-ю – 4 зерна, …)

Формат входных данных
Цлое число от 1 до 64
Формат результата
Одно целое число. Количество зерен на данной клетке.
Примеры
Входные данные
3
Результат работы
4
Входные данные
28
Результат работы
134217728
*/

#define MIN_CELL 1U
#define MAX_CELL 64U

uint64_t grains_on_cell(uint32_t n);

int main(void)
{
    uint32_t n = 0;

    if (scanf("%" SCNu32, &n) != 1)
    {
        return EXIT_FAILURE;
    }

    if (n < MIN_CELL || n > MAX_CELL)
    {
        return EXIT_FAILURE;
    }

    uint64_t result = grains_on_cell(n);

    printf("%" PRIu64 "\n", result);

    return EXIT_SUCCESS;
}

uint64_t grains_on_cell(uint32_t n) { return ((uint64_t)1) << (n - 1U); }
